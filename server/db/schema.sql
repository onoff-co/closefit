CREATE TABLE IF NOT EXISTS members (
 id CHAR(36) PRIMARY KEY,
 username VARCHAR(30) NOT NULL UNIQUE,
 email VARCHAR(150) NOT NULL UNIQUE,
 name VARCHAR(40) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('customer','admin') NOT NULL DEFAULT 'customer',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, sub VARCHAR(250) NOT NULL DEFAULT '',
 price INT NOT NULL, category VARCHAR(30) NOT NULL, tag VARCHAR(20) NOT NULL, colors JSON NOT NULL,
 image VARCHAR(160) NOT NULL, stock INT NOT NULL DEFAULT 50, active BOOLEAN NOT NULL DEFAULT TRUE,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK(price>=0), CHECK(stock>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
 id CHAR(36) PRIMARY KEY, user_id CHAR(36) NULL, customer VARCHAR(40) NOT NULL, email VARCHAR(150) NOT NULL,
 total INT NOT NULL, status ENUM('pending','paid','shipping','completed','cancelled') NOT NULL DEFAULT 'pending',
 note VARCHAR(500) NOT NULL DEFAULT '', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES members(id) ON DELETE SET NULL, INDEX orders_user_date(user_id,created_at),
 CHECK(total>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id CHAR(36) NOT NULL, product_id INT NULL,
 name VARCHAR(100) NOT NULL, price INT NOT NULL, qty INT NOT NULL, color VARCHAR(40) NOT NULL, size VARCHAR(5) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL,
 CHECK(price>=0), CHECK(qty>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY, member_id CHAR(36) NOT NULL, expires_at DATETIME NOT NULL,
 FOREIGN KEY(member_id) REFERENCES members(id) ON DELETE CASCADE, INDEX session_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payment_keys (
 user_id CHAR(36) NOT NULL, payment_key VARCHAR(100) NOT NULL, order_id CHAR(36) NULL,
 PRIMARY KEY(user_id,payment_key), FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id CHAR(36) PRIMARY KEY, actor CHAR(36) NOT NULL, action VARCHAR(80) NOT NULL, target VARCHAR(100) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS visits (
 id VARCHAR(255) PRIMARY KEY, visitor VARCHAR(64) NOT NULL, path VARCHAR(150) NOT NULL, device VARCHAR(10) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX visit_date(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
